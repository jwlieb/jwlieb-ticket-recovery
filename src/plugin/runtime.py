"""Controlled task tools. Candidate code never receives the evaluator or receipt paths."""

from __future__ import annotations

import hashlib
import json
import secrets
from pathlib import Path

from slimconfig import build_output, plain_output
from contract import AssessmentOutput, EditOutput, InspectionOutput, ReferenceOutput, TaskInput
from plugin import domain
from verifier.oracle import expected


def canonical(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False)


def digest(files):
    return hashlib.sha256(canonical(files).encode()).hexdigest()


def candidate_files(workspace):
    root = Path(workspace).resolve()
    files = {}
    for name in domain.STARTER:
        p = root / "candidate" / name
        if p.is_symlink() or not p.is_file() or not p.resolve().is_relative_to(root):
            raise ValueError(f"Missing or unsafe candidate: {name}")
        files[name] = p.read_text()
    return files


def pin_reference(value, workspace):
    raw = canonical(domain.fixture(value.scenario.value, value.seed))
    observations = {k: canonical(v) for k, v in expected(json.loads(raw)).items()}
    return ReferenceOutput(value, raw, hashlib.sha256(raw.encode()).hexdigest(), observations)


def inspect_task(value, workspace):
    if not 0 <= value.seed <= 9999:
        raise ValueError("seed must be 0 through 9999")
    root = Path(workspace).resolve()
    root.mkdir(parents=True, exist_ok=True)
    state = root / "state.json"
    task = plain_output(value)
    if state.is_symlink():
        raise ValueError("unsafe state path")
    if state.exists():
        if json.loads(state.read_text()) != task:
            raise ValueError("A workspace belongs to exactly one task input; use a fresh workspace")
    else:
        state.write_text(canonical(task))
        for name, contents in domain.STARTER.items():
            target = root / "candidate" / name
            if target.is_symlink() or not target.resolve().is_relative_to(root):
                raise ValueError("unsafe candidate path")
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(contents)
    return InspectionOutput(
        value, domain.SPEC, candidate_files(root), canonical(domain.fixture(value.scenario.value, value.seed))
    )


def edit_files(value, workspace):
    if not value.files or not set(value.files) <= set(domain.STARTER):
        raise ValueError("Only the named candidate files may be edited")
    for name, contents in value.files.items():
        if not isinstance(contents, str) or len(contents.encode()) > 24000:
            raise ValueError("Each candidate must be UTF-8 text, at most 24 KB")
        p = Path(workspace) / "candidate" / name
        if p.is_symlink() or not p.is_file():
            raise ValueError("inspect_task must initialize regular candidate files first")
        p.write_text(contents)
    return EditOutput(digest(candidate_files(workspace)), sorted(value.files))


def assess(value, workspace):
    root = Path(workspace).resolve()
    task = build_output(json.loads((root / "state.json").read_text()), TaskInput)
    raw = domain.fixture(task.scenario.value, task.seed)
    files = candidate_files(root)
    artifact = digest(files)
    diagnostics = ""
    # Assessments are generated by trusted code; no tool accepts measurements or receipt contents.
    try:
        measured = domain.measure(files, raw, root)
        measurements = {k: canonical(v) for k, v in measured.items()}
    except Exception as error:
        measurements = {"execution_error": canonical(f"{type(error).__name__}: {error}")}
        diagnostics = f"{type(error).__name__}: {error}"[-1800:]
    expectations = {k: canonical(v) for k, v in expected(raw).items()}
    failures = sorted(k for k in set(expectations) | set(measurements) if expectations.get(k) != measurements.get(k))
    assessment_id = secrets.token_hex(12)
    receipt = {
        "task": plain_output(task),
        "artifact_sha256": artifact,
        "fixture_sha256": hashlib.sha256(canonical(raw).encode()).hexdigest(),
        "measurements": measurements,
        "failures": failures,
        "result_files": {},
    }
    # Bind persistent results as well as the repair/plan that produced them.
    for name in domain.RESULT_FILES:
        p = root / name
        if p.is_file() and not p.is_symlink():
            receipt["result_files"][name] = hashlib.sha256(p.read_bytes()).hexdigest()
    receipts = root / "receipts"
    receipts.mkdir(exist_ok=True)
    (receipts / f"{assessment_id}.json").write_text(canonical(receipt))
    if failures and not diagnostics:
        first = failures[0]
        diagnostics = f"{first}: measured {measurements.get(first, 'missing')}"[:1800]
    return AssessmentOutput(assessment_id, artifact, not failures, failures, diagnostics)
